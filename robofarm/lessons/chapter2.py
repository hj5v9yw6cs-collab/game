def _data(count_for=(12, 9, 10), **kw):
    def data(variant):
        n = count_for[min(variant, len(count_for) - 1)]
        return {"beds": field_beds(variant, n, **kw)}
    return data


def beds(r):
    return r.input.get("beds", [])


def names(r, cond=lambda b: True):
    return [b["name"] for b in beds(r) if cond(b)]


def ripe(b):
    return b["stage"] == "ripe"


def dry(b):
    return b["humidity"] < 40


# ---------------------------------------------------------------- урок 5: списки

def _second(r):
    if not r.printed_number(9):
        return "Нужно напечатать 9 — второй элемент. Индексы начинаются с нуля: первый — [0], второй — [1]."
    if "print(9)" in r.code.replace(" ", ""):
        return "Возьми число из списка по индексу, а не вписывай его руками: урожай[...]."
    return None


def _last(r):
    if not r.printed_number(6):
        return "Последний элемент — 6. В списке из трёх элементов индексы 0, 1 и 2."
    return None


def _quest5(r):
    def check(v):
        bs = names(v)
        w = v.watered()
        if bs[0] not in w:
            return f"Первая грядка ({bs[0]}) не полита. Первая — поле[0]."
        if bs[-1] not in w:
            return f"Последняя грядка ({bs[-1]}) не полита. Последнюю удобно взять так: поле[-1]."
        if len(set(w)) > 2:
            return "Полить нужно только первую и последнюю грядки."
        if not v.printed_number(len(bs)):
            return "Напечатай, сколько грядок в поле: print(len(поле))."
        return None
    msg = r.each(check)
    if msg:
        return msg
    if r.calls("len") == 0:
        return "Число грядок посчитай командой len(поле): вдруг Михалыч отдаст ещё грядок."
    return None


# ---------------------------------------------------------------- урок 6: цикл for

def _harvest_all(r):
    visited = {e["bed"] for e in r.acts("harvest")}
    if visited != set(names(r)):
        return (f"Бублик подошёл к {len(visited)} грядкам из {len(beds(r))}. "
                "Внутри цикла нужна команда собрать(грядка) — для текущей грядки, с отступом.")
    return None


def _water_all(r):
    missing = [n for n in names(r) if n not in r.watered()]
    if missing:
        return f"Не политы: {', '.join(missing)}. Проверь двоеточие после for и отступ у полить(грядка)."
    return None


def _robots(r):
    want = ["Клуша", "Бублик", "Мурзик"]
    if not all(r.printed(w) for w in want):
        return "Нужно напечатать имя каждого робота из списка — print внутри цикла."
    if r.node_count(__import__("ast").For) == 0:
        return "Сделай это циклом for, а не тремя командами print: в настоящих списках бывают тысячи элементов."
    return None


def _quest6(r):
    def check(v):
        missing = [n for n in names(v) if n not in v.watered()]
        if missing:
            return f"Не политы грядки: {', '.join(missing)}."
        if not v.printed_number(len(names(v))):
            return (f"Нужно напечатать, сколько грядок полито ({len(names(v))}). Заведи счётчик: "
                    "полито = 0 до цикла и полито = полито + 1 внутри.")
        return None
    msg = r.each(check)
    if msg:
        return msg
    if r.node_count(__import__("ast").For) == 0:
        return "Используй цикл for: так программа польёт любое поле, хоть из ста грядок."
    return None


# ---------------------------------------------------------------- урок 7: условия

def _ripe_only(r):
    want, got = set(names(r, ripe)), set(r.harvested())
    if r.harvested(ok=False):
        return "Бублик пытался собрать неспелые грядки. Условие должно пропускать только спелые: == True."
    if got != want:
        return f"Собраны не все спелые грядки. Должны быть: {', '.join(sorted(want))}."
    return None


def _eq_fix(r):
    want = names(r, lambda b: b["humidity"] == 100)
    if not all(r.printed(n) for n in want):
        return "Должны напечататься грядки с влажностью 100. Для сравнения нужно «==»."
    return None


def _quest7(r):
    def check(v):
        if v.harvested(ok=False):
            return "Бублик дёргал неспелые грядки — собирай только спелые."
        if set(v.watered()) != set(names(v, dry)):
            extra = set(v.watered()) - set(names(v, dry))
            if extra:
                return f"Политы мокрые грядки: {', '.join(sorted(extra))}. Поливать нужно, только если влажность меньше 40."
            return f"Не политы сухие грядки: {', '.join(sorted(set(names(v, dry)) - set(v.watered())))}."
        if set(v.harvested()) != set(names(v, ripe)):
            return f"Собраны не все спелые грядки: нужно {', '.join(names(v, ripe))}."
        return None
    return r.each(check)


# ---------------------------------------------------------------- урок 8: and/or и счётчики

def _dry_count(r):
    def check(v):
        if not v.printed_number(len(names(v, dry))):
            return f"Сухих грядок {len(names(v, dry))}, а напечатано другое. Счётчик увеличивается на 1."
        return None
    return r.each(check)


def _carrot_or_cabbage(r):
    want = names(r, lambda b: b["crop"] in ("морковь", "капуста"))
    if not all(r.printed(n) for n in want):
        return "Нужны все грядки, где культура — морковь или капуста. Условие: ... == \"морковь\" or ... == \"капуста\"."
    unwanted = [n for n in names(r, lambda b: b["crop"] == "тыква") if any(line.strip() == n for line in r.lines)]
    if unwanted:
        return f"Напечатаны лишние грядки с тыквой: {', '.join(unwanted)}."
    return None


def _quest8(r):
    def check(v):
        total = sum(b["kg"] for b in beds(v) if ripe(b))
        pumpkins = sum(b["kg"] for b in beds(v) if ripe(b) and b["crop"] == "тыква")
        if set(v.harvested()) != set(names(v, ripe)):
            return "Собери все спелые грядки."
        if not v.printed_number(total):
            return f"Всего собрано {total} кг — это число нужно напечатать. Складывай то, что возвращает собрать()."
        if not v.printed_number(pumpkins):
            return f"Тыквы собрано {pumpkins} кг. Нужен второй счётчик — только для тыквы (and)."
        return None
    return r.each(check)


