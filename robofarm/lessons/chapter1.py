def _carrot_var(r):
    if "морковь" not in r.harvested():
        return "Сначала собери морковь: в кавычках должно быть \"морковь\"."
    if r.printed("морковь_кг"):
        return ("Бублик напечатал слово «морковь_кг», а нужно число из ящика. "
                "Убери кавычки: print(морковь_кг).")
    if not r.printed_number(4):
        return "Нужно напечатать, что лежит в ящике морковь_кг. Впиши его имя в print(...)."
    return None


def _cabbage_print(r):
    if not r.printed_number(6):
        return "Нужно напечатать вес капусты из ящика «капуста»."
    return None


def _quest3(r):
    for name, kg, crop in (("тыква_кг", 9, "тыкву"), ("морковь_кг", 4, "морковь")):
        if not r.has_var(name):
            return f"Нет ящика «{name}». Создай его: {name} = собрать(...) — собери в него {crop}."
        if r.var(name) != kg:
            return f"В ящике «{name}» лежит {r.var(name)!r}, а должно быть {kg}. Проверь, что собираешь {crop}."
    if not (r.printed_number(9) and r.printed_number(4)):
        return "Ящики готовы, осталось напечатать оба числа для Михалыча: print(тыква_кг) и print(морковь_кг)."
    return None


