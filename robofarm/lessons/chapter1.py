def _money(r):
    if r.var("деньги") != 270:
        if r.has_var("деньги"):
            return (f"В ящике «деньги» лежит {r.var('деньги')}, а должно быть 9 кг × 30 руб. = 270. "
                    "Какой знак означает «умножить»?")
        return "Впиши знак действия вместо ____. Умножение в Python — звёздочка *."
    return None


def _concat_fixed(r):
    if not (r.printed("тыквы") and r.printed_number(9)):
        return "Нужно напечатать «Тыквы:» и число 9 в одной строке. Подсказка: в print значения разделяются запятой."
    return None


def _quest4(r):
    if not r.printed_number(470):
        got = [line for line in r.lines]
        hint = f" Сейчас напечатано: {got[-1]!r}." if got else ""
        return ("Итог должен быть 9 кг × 30 руб. + 4 кг × 50 руб. = 470 руб. "
                "Посчитай в коде и напечатай." + hint)
    if "тыква" not in r.harvested() or "морковь" not in r.harvested():
        return "Число верное, но урожай-то не собран! Пусть Бублик соберёт тыкву и морковь командой собрать(...)."
    if r.calls("собрать") == 0:
        return "Посчитай через собранный урожай: тыква = собрать(\"тыква\")."
    return None


