# ---------------------------------------------------------------- проверки урока 1

def _said_something(r):
    if not r.lines:
        return "Бублик промолчал. Чтобы он заговорил, нужна команда print(...) с текстом в кавычках."
    if any("____" in line for line in r.lines):
        return "Замени ____ на свои слова — например, на «Привет, Клуша!»."
    return None


def _said_privet(r):
    if not r.printed("привет"):
        return "Бублик должен сказать «Привет». Проверь, что слово стоит внутри кавычек."
    return None


def _two_lines(r):
    if len(r.lines) < 2:
        return ("Нужно две строки — значит, две команды print, каждая на своей строке. "
                f"Сейчас Бублик сказал строк: {len(r.lines)}.")
    if "бублик" not in r.lines[0].lower():
        return "В первой строке Бублик должен назвать себя: «Я Бублик»."
    if "готов" not in r.lines[1].lower():
        return "Во второй строке нужно «Я готов работать!» — команды выполняются по порядку, сверху вниз."
    return None


def _quest1(r):
    if len(r.lines) < 3:
        return (f"Михалыч хочет услышать три вещи, а Бублик сказал строк: {len(r.lines)}. "
                "Нужно три команды print: как зовут, чей он и что умеет.")
    if not any("бублик" in line.lower() for line in r.lines):
        return "Бублик забыл назвать своё имя."
    return None


# ---------------------------------------------------------------- проверки урока 2

def _watered(name):
    def check(r):
        w = r.watered()
        if name not in w:
            if w:
                return f"Бублик полил «{w[0]}», а нужно «{name}». Поменяй название в кавычках."
            return f"Бублик ничего не полил. Нужна команда полить(\"{name}\")."
        return None
    return check


def _watered_all(r):
    missing = [b for b in ("морковь", "тыква", "капуста") if b not in r.watered()]
    if missing:
        return "Остались сухими: " + ", ".join(missing) + ". Для каждой грядки — своя команда полить(...)."
    return None


def _quest2(r):
    missing = [b for b in ("морковь", "тыква", "капуста") if b not in r.watered()]
    if missing:
        return "Не политы: " + ", ".join(missing) + "."
    got = r.harvested()
    if "тыква" not in got or "морковь" not in got:
        need = [b for b in ("тыква", "морковь") if b not in got]
        return "Ещё не собраны: " + ", ".join(need) + ". Нужна команда собрать(...)."
    if "капуста" in r.harvested(ok=False):
        return "Капуста ещё растёт — Бублик зря её дёргал. Убери команду собрать(\"капуста\")."
    return None


